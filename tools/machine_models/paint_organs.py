"""Block in the flora implements' diffuse paintings on a 28-texel canvas."""
from pathlib import Path
from PIL import Image, ImageDraw


def panel(ramp, shapes):
    colors = ["#" + ink for ink in ramp.split()]
    im = Image.new("RGB", (28, 28), colors[0])
    pen = ImageDraw.Draw(im)
    for tone, outline in shapes:
        pen.polygon([tuple(map(int, point.split(","))) for point in outline.split()], fill=colors[tone])
    return im


