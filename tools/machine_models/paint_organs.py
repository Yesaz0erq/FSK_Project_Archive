def main():
    atlas = Image.new("RGB", (128, 128))
    for i, (shapes, ramp) in enumerate(PANELS):
        paint = panel(ramp, shapes)
        # Two duplicated edge texels isolate adjacent materials at a distance.
        tile = Image.new("RGB", (32, 32))
        tile.paste(paint, (2, 2))
        for x, sx in [(0, 0), (30, 27)]:
            tile.paste(paint.crop((sx, 0, sx + 1, 28)).resize((2, 28)), (x, 2))
        for y, sy in [(0, 2), (30, 29)]:
            tile.paste(tile.crop((0, sy, 32, sy + 1)).resize((32, 2)), (0, y))
        atlas.paste(tile, (i % 4 * 32, i // 4 * 32))
    atlas.save(Path(__file__).resolve().parents[2] / "assets/models/flora/organ_paint.png")


if __name__ == "__main__":
    main()
